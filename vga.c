/* Draw a pixel at (x, y) with color */
void
vgaPutPixel(int x, int y, uchar color)
{
  if(x < 0 || x >= 320 || y < 0 || y >= 200)
    return;
  
  volatile uchar *vga = (uchar *)P2V(0xA0000);
//   volatile uchar *vga = (uchar *)(0xA0000);
  vga[y * 320 + x] = color;
}

/* Draw a filled rectangle */
void
vgaFillRect(int x, int y, int w, int h, uchar color)
{
  int i, j;
  for(i = y; i < y + h && i < 200; i++) {
    for(j = x; j < x + w && j < 320; j++) {
      vgaPutPixel(j, i, color);
    }
  }
}

/* Clear screen with color */
void
vgaClear(uchar color)
{
  vgaFillRect(0, 0, 320, 200, color);
}

/* Draw a circle */
void
vgaDrawCircle(int cx, int cy, int r, uchar color)
{
  int x, y;
  for(y = cy - r; y <= cy + r && y >= 0 && y < 200; y++) {
    for(x = cx - r; x <= cx + r && x >= 0 && x < 320; x++) {
      int dx = x - cx;
      int dy = y - cy;
      if(dx*dx + dy*dy <= r*r) {
        vgaPutPixel(x, y, color);
      }
    }
  }
}

// Kernel-mode VGA functions for syscalls
// These run in kernel context and can access VGA memory directly

int
vgaMemTest(void)
{
  volatile uchar *vga = (uchar *)P2V(0xA0000);
  // Try to write and read a test value
  uchar orig = vga[0];
  vga[0] = 0xAA;
  uchar test = vga[0];
  vga[0] = orig;
  return (test == 0xAA) ? 1 : 0;
}

void
vgaKernelFillRect(int x, int y, int w, int h, uchar color)
{
  vgaFillRect(x, y, w, h, color);
}

void
vgaKernelDrawCircle(int cx, int cy, int r, uchar color)
{
  vgaDrawCircle(cx, cy, r, color);
}