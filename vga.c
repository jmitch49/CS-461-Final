int cga256[256];

/* VGA register I/O functions */
static void
write3C0(unsigned char index, unsigned char value)
{
  inb(0x3DA);
  outb(0x3C0, index);
  outb(0x3C0, value);
}

static void
write3C2(unsigned char value)
{
  outb(0x3C2, value);
}

static void
write3C4(unsigned char index, unsigned char value)
{
  outb(0x3C4, index);
  outb(0x3C5, value);
}

static void
write3CE(unsigned char index, unsigned char value)
{
  outb(0x3CE, index);
  outb(0x3CF, value);
}

static void
write3D4(unsigned char index, unsigned char value)
{
  outb(0x3D4, index);
  outb(0x3D5, value);
}

static void
vgaSetPalette(int index, int r, int g, int b)
{
  outb(0x3C8, index);
  outb(0x3C9, r);
  outb(0x3C9, g);
  outb(0x3C9, b);
}

static void
setdefaultVGApalette(void)
{
  for(int i = 0; i < 256; i++) {
    int value = vga256_24bit[i];
    vgaSetPalette(i,
        (value >> 18) & 0x3f,
        (value >> 10) & 0x3f,
        (value >> 2) & 0x3f);
  }
}

static void
cgaSavePalette(void)
{
  outb(0x3C7, 0);
  for(int i = 0; i < 256; i++) {
    int r = inb(0x3C9);
    int g = inb(0x3C9);
    int b = inb(0x3C9);
    cga256[i] = (r << 16) | (g << 8) | b;
  }
}

static void
cgaRestorePalette(void)
{
  outb(0x3C8, 0);
  for(int i = 0; i < 16; i++) {
    int color = cga256[i];
    outb(0x3C9, (color >> 16) & 0xFF);
    outb(0x3C9, (color >> 8) & 0xFF);
    outb(0x3C9, color & 0xFF);
  }
}

